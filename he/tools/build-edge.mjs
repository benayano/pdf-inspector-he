// Builds the Supabase Edge / Deno package: one directory with no binary
// file in it, so it deploys anywhere code is deployed as text (an Edge
// Function upload, a vendored folder in another repository).
//
//   node he/tools/build-edge.mjs wasm/pkg-web out/pdf-inspector-he-edge
//
// - pdf_inspector.js / .d.ts      the wasm-bindgen `web` build (has initSync)
// - pdf_inspector_wasm.js         the .wasm, gzip + base64 (~3.5 MB of text)
// - edge.mjs / edge.d.ts          `await load()` -> the ready module; unpacks
//                                 once per isolate (DecompressionStream)
// - invoice.mjs, repair.mjs, document.mjs, agent.mjs, rtl-check.mjs and their
//   .d.ts, and invoice-document.schema.json
// - VERSION.json                  the commit, the build date and the sha-256
//                                 of the .wasm, so a vendored copy says what it is
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { gzipSync } from "node:zlib";

const [pkgWeb, outDir] = process.argv.slice(2);
if (!pkgWeb || !outDir) {
  console.error("usage: node he/tools/build-edge.mjs <wasm/pkg-web> <out dir>");
  process.exit(2);
}
const he = resolve(new URL("..", import.meta.url).pathname);
mkdirSync(outDir, { recursive: true });

const wasm = readFileSync(join(pkgWeb, "pdf_inspector_bg.wasm"));
const gz = gzipSync(wasm, { level: 9 });
writeFileSync(
  join(outDir, "pdf_inspector_wasm.js"),
  "// Generated by he/tools/build-edge.mjs: pdf_inspector_bg.wasm, gzip, base64. Do not edit.\n" +
    `export const WASM_GZIP_BASE64 = "${gz.toString("base64")}";\n`,
);
for (const f of ["pdf_inspector.js", "pdf_inspector.d.ts"]) copyFileSync(join(pkgWeb, f), join(outDir, f));
for (const f of ["invoice.mjs", "invoice.d.ts", "repair.mjs", "repair.d.ts", "document.mjs", "document.d.ts", "agent.mjs", "agent.d.ts", "invoice-document.schema.json", "rtl-check.mjs", "rtl-check.d.ts"]) {
  copyFileSync(join(he, f), join(outDir, f));
}

writeFileSync(
  join(outDir, "edge.mjs"),
  `// Generated by he/tools/build-edge.mjs. Loads pdf-inspector-he from the
// embedded wasm: \`const pdf = await load()\`, then pdf.processPdf(...) etc.
import * as pdf from "./pdf_inspector.js";
import { WASM_GZIP_BASE64 } from "./pdf_inspector_wasm.js";

let ready = null;

async function unpack() {
  const binary = atob(WASM_GZIP_BASE64);
  const gz = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) gz[i] = binary.charCodeAt(i);
  const stream = new Blob([gz]).stream().pipeThrough(new DecompressionStream("gzip"));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

/** The pdf-inspector module, ready to call. Unpacks the wasm once per isolate. */
export function load() {
  ready ??= unpack().then((bytes) => {
    pdf.initSync({ module: bytes });
    return pdf;
  });
  return ready;
}
`,
);
writeFileSync(
  join(outDir, "edge.d.ts"),
  `import type * as pdf from "./pdf_inspector.js";\n/** The pdf-inspector module, ready to call. */\nexport function load(): Promise<typeof pdf>;\n`,
);

let commit = "unknown";
try {
  commit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: he }).toString().trim();
} catch {}
writeFileSync(
  join(outDir, "VERSION.json"),
  JSON.stringify(
    {
      package: "pdf-inspector-he-edge",
      commit,
      built: new Date().toISOString(),
      wasm_sha256: createHash("sha256").update(wasm).digest("hex"),
      wasm_bytes: wasm.length,
      gzip_bytes: gz.length,
    },
    null,
    2,
  ) + "\n",
);
console.log(`edge package: ${outDir} (wasm ${wasm.length} B, gzip ${gz.length} B)`);
